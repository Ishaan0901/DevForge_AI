from langchain_core.tools import tool
import subprocess
import os

#           TOOL-1: Write_Code...
@tool
def write_code(code:str):
    '''
    This tool takes the Code generated by the LLM and saves it in generated_code.py file .
    '''

    code=code.replace('```python','').replace('```','')
    try:
        with open('generated_code.py','w',encoding='utf-8') as c:
            c.write(code)
        return ('Code written in generated_code.py successfully')
    except Exception as e:
        return (f'error occured....{e}')



#           TOOL-2: Execute_Code...
@tool
def execute_code(file_name: str = "generated_code.py"):
    '''Runs generated_code.py and returns output, error and exit code.'''
    try:
        result = subprocess.run(
            ["python", file_name],
            capture_output=True,
            text=True,
            timeout=10
        )
        return {
            "output": result.stdout,
            "error": result.stderr,
            "exit_code": result.returncode
        }

    except subprocess.TimeoutExpired:
        return {"output": "", "error": "Timeout: code took more than 10 seconds", "exit_code": -1}
    
    except Exception as e:
        return {"output": "", "error": str(e), "exit_code": -1}


#           TOOL-3: Check_result...
@tool
def check_result(result:dict)->str:
    '''
    This tool takes the result dictionary from execute_code tool and returns success if the code ran successfully
    '''

    if result['exit_code']==0:
        return('Code executed successfully')

    else :
        return(f'There was an error while executing the code!! \n\n{result["error"]}')



#          TOOL-4: Website Developer...
@tool
def write_html_code(code:str):
    '''
    This tool takes the Code generated by the LLM and saves it in index.html file .
    '''
    code=code.replace('```html','').replace('```','')
    try:
        os.makedirs("website", exist_ok=True)
        with open('website/index.html','w',encoding='utf-8') as c:
            c.write(code)
        return ('Code written in website/index.html successfully')
    except Exception as e:
        return (f'error occured....{e}')